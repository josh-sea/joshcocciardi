/* Builds js/race-puzzles.js, the Word Race puzzles, from SCOWL.
 *
 * Every puzzle is a common eight-letter word whose letters go round the
 * wheel, plus every word those letters can make. Working the answers out
 * here rather than in the browser means the game ships no dictionary at
 * all: the host checks a guess against the puzzle's own list.
 *
 *   common  SCOWL sizes 10 and 20: words everyone knows. Seeds come from here
 *           and so does the reveal at the end of a round.
 *   rare    sizes 35 to 50: real words a grown-up might know ("tarn",
 *           "gelt"). They score, but the reveal doesn't shame anyone for
 *           missing them.
 *
 * Anything on the LDNOOBW list, or on the extra list below, is left out of
 * both, and a seed is never a word that could make one.
 *
 * Run (from the repo root):
 *   npm --prefix /tmp/words install --no-save wordlist-english naughty-words
 *   node apps/party-room/scripts/build-race.mjs /tmp/words/node_modules
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const mods = process.argv[2];
if (!mods) { console.error('usage: build-race.mjs <node_modules with wordlist-english and naughty-words>'); process.exit(1); }
const here = dirname(fileURLToPath(import.meta.url));
const load = (f) => JSON.parse(readFileSync(join(mods, f), 'utf8'));

const COMMON = [10, 20], RARE = [35, 40, 50];
const words = (sizes) => {
  const out = new Set();
  for (const n of sizes) for (const v of ['english', 'american']) {
    for (const w of load(`wordlist-english/${v}-words-${n}.json`)) if (/^[a-z]{3,8}$/.test(w)) out.add(w);
  }
  return out;
};

// Not slurs or swearing, just not what you want flashing up on Grammy's phone.
const EXTRA = `anal anus arse bra bras butt butts crap crappy damn dang drug drugs drunk faggot fart farts
  heroin hell hells horny kill killer kills knob nazi nude nudes opium pee pees piss poo poop porn prat
  rape raped rapes rapist sex sexy slut stoned suck sucks teat tit tits turd vomit weed whore wino`;
const bad = new Set([...load('naughty-words/en.json'), ...EXTRA.split(/\s+/)].map((w) => String(w).toLowerCase()));

const common = words(COMMON);
const rare = words(RARE);
for (const w of [...common, ...rare]) if (bad.has(w)) { common.delete(w); rare.delete(w); }
for (const w of common) rare.delete(w);

const counts = (w) => { const c = {}; for (const ch of w) c[ch] = (c[ch] || 0) + 1; return c; };
const fits = (w, pool) => { const c = counts(w); return Object.keys(c).every((k) => (pool[k] || 0) >= c[k]); };
// A bit per letter, so most words are ruled out with one AND.
const mask = (w) => { let m = 0; for (const ch of w) m |= 1 << (ch.charCodeAt(0) - 97); return m; };
const index = (set) => [...set].map((w) => ({ w, m: mask(w) }));
const commonIx = index(common), rareIx = index(rare);
const within = (ix, m, pool) => ix.filter((e) => (e.m & ~m) === 0 && fits(e.w, pool)).map((e) => e.w);

// Same idea as room.js: seeded, so a rebuild makes the same file.
let s = 20201;
const rand = () => { s = (s * 1103515245 + 12345) % 2147483648; return s / 2147483648; };

const seeds = [...common].filter((w) => w.length === 8).sort();
const puzzles = [];
const seen = new Set();
for (const seed of seeds) {
  const key = [...seed].sort().join('');
  if (seen.has(key)) continue; // "parental" and "paternal" are one puzzle
  seen.add(key);
  const pool = counts(seed);
  const m = mask(seed);
  const c = within(commonIx, m, pool);
  const r = within(rareIx, m, pool);
  // Too few and the round is over in ten seconds; too many and the reveal is a wall.
  if (c.length < 12 || c.length > 60 || c.length + r.length > 130) continue;
  if (!c.some((w) => w.length === 8)) continue;
  puzzles.push({ key, c: c.sort((a, b) => a.length - b.length || a.localeCompare(b)), r: r.sort() });
}
// Shuffle, keep a few hundred.
for (let i = puzzles.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [puzzles[i], puzzles[j]] = [puzzles[j], puzzles[i]]; }
const keep = puzzles.slice(0, 400).sort((a, b) => a.key.localeCompare(b.key));

const body = keep.map((p) => `  [${JSON.stringify(p.key)}, ${JSON.stringify(p.c.join(' '))}, ${JSON.stringify(p.r.join(' '))}],`).join('\n');
writeFileSync(join(here, '../js/race-puzzles.js'), `/* Word Race puzzles. Generated by scripts/build-race.mjs from SCOWL; do not edit.
 *
 * [letters, common answers, rare answers]. Word lists from SCOWL,
 * Copyright 2000-2016 by Kevin Atkinson, used under its permissive licence
 * (see CREDITS.md). Offensive words removed using the LDNOOBW list
 * (CC BY 4.0).
 */
export const PUZZLES = [
${body}
];
`);
console.log(`${seeds.length} eight-letter seeds, ${puzzles.length} usable, kept ${keep.length}`);
